def parse(src):
    d={}
    for line in src.strip().splitlines():
        vals=list(map(int,line.split()))
        assert len(vals)>=4 and len(vals)<=8,(line,len(vals))
        k,base,*y=vals
        d[k]={'base':base,'values':y+[None]*(6-len(y))}
    return d

